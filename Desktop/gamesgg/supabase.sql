-- API gamesgg: base de datos de videojuegos para Supabase
-- Abre el SQL Editor de Supabase, pega este archivo y pulsa Run.

create table if not exists public.videojuegos (
    id bigint generated by default as identity primary key,
    titulo text not null,
    genero text not null,
    plataforma text not null,
    anio integer not null check (anio between 1950 and 2100),
    nota numeric(3,1) not null check (nota between 1 and 10),
    constraint videojuegos_titulo_plataforma_unique unique (titulo, plataforma)
);

-- Datos iniciales. ON CONFLICT evita duplicarlos si ejecutas el archivo otra vez.
insert into public.videojuegos (titulo, genero, plataforma, anio, nota)
values
    ('Minecraft', 'Sandbox', 'PC', 2011, 9.5),
    ('The Legend of Zelda: Breath of the Wild', 'Aventura', 'Nintendo Switch', 2017, 9.8),
    ('Grand Theft Auto V', 'Accion', 'PlayStation 5', 2013, 9.2),
    ('Stardew Valley', 'Simulacion', 'PC', 2016, 9.0),
    ('Super Mario Odyssey', 'Plataformas', 'Nintendo Switch', 2017, 9.4)
on conflict (titulo, plataforma) do nothing;

-- SELECT: listar todos los videojuegos.
select * from public.videojuegos order by id;

-- SELECT con filtro: buscar por género.
select * from public.videojuegos
where lower(genero) = lower('Aventura');

-- SELECT con filtro: buscar por plataforma.
select * from public.videojuegos
where lower(plataforma) = lower('PC');

-- SELECT por ID.
select * from public.videojuegos where id = 1;

-- INSERT: agregar un videojuego. El ID se genera automáticamente.
insert into public.videojuegos (titulo, genero, plataforma, anio, nota)
values ('Hollow Knight', 'Metroidvania', 'PC', 2017, 9.7)
returning *;

-- UPDATE: modificar un videojuego existente.
update public.videojuegos
set nota = 9.8
where id = 1
returning *;

